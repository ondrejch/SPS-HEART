#!/usr/bin/env python3
"""Regenerate the committed mini-pipeline fixture for the offline smoke run.

The fixture under ``mini_pipeline/fixture/`` drives ``run_smoke.sh``: one
complete production fit-to-assets path of
``helpers/benchmarking/benchmark_multispecies_constrained.py`` with no
network access, no ``spshadrons.web.cern.ch/`` tables, no external
generators, and no UrQMD tarball. Every number in the fixture is synthetic
Monte Carlo output of the bundled ``na49_mixing`` decay generator or a
fixture constant written by this script, so the whole directory is legally
redistributable.

Fixture contents
----------------

``resonance_component_cache/``
    Component-cache NPZ files written by the production caching path
    (``benchmark_sps_species._build_resonance_component_cache``) for the
    full resonance spec list the benchmark driver assembles with the Regge
    tower disabled. Each component is generated with a small event count
    (``FIXTURE_EVENTS_PER_RES``) and the pinned seed below, so the smoke
    run reuses the committed cache unchanged instead of regenerating
    tracks. The cache metadata (decay-library fingerprint, component
    seeds, fragmentation mode, weak-feed policy, nucleus payload) is
    computed from the current source tree exactly as the driver computes
    it, which is what makes the reuse check pass. If the fingerprinted
    ``na49_mixing`` modules change, the smoke run rebuilds the cache into
    its own output directory (offline, seconds at this event count) and
    the pinned reference numbers must be re-recorded; regenerate this
    fixture with this script in that case.

``absyield_prior.json``
    Absolute-yield prior targets and uncertainties for pi- and pi+. The
    values are round-number fixture constants placed near the integrated
    yield scale of the committed reduced NA49 p+Pb pion tables; they are
    not measured quantities and not derived at run time.

``fixture_manifest.json``
    What this script built: parameters, expected file count, and total
    size, so a checkout can verify the fixture against its generator.

Why the design is full rank by construction
-------------------------------------------

The identifiability policy refuses a rank-deficient fit design by default.
Two construction rules keep the fixture design full rank:

1. Every committed component column is generated by the production
   assembly path from independently seeded tracks (one seed per spec key,
   derived from sha1 of the namespace-qualified spec key), so distinct
   components carry distinct kinematic distributions. No column is a
   multiple of another and no two columns share a random stream.
2. Components that produce no tracks of any loaded species would enter
   the stacked design as identically zero columns. The benchmark driver
   drops such components before assembly (recorded under
   ``resonance.dropped_zero_column_components`` in the summary), so with
   the pion-only species set of the smoke run the phi_1020 component
   (which decays to K+K- only) is excluded by the driver and the remaining
   columns span the full component space. The smoke validation asserts
   ``design_rank == n_components`` and the ``full_rank_identifiable``
   stamp, so a fixture that drifted to rank deficiency fails the run
   instead of silently passing.

Usage
-----

Run from anywhere with the mixing2006 tree importable (the script inserts
its own repository root on ``sys.path``)::

    python sps_resonances_paper/mini_pipeline/make_fixture.py
    python sps_resonances_paper/mini_pipeline/make_fixture.py --output-dir <dir>

The committed fixture is generated with the exact parameters the smoke run
uses; do not change the constants without re-recording the pinned reference
numbers in ``expected_smoke.py``.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

MINI_PIPELINE_DIR = Path(__file__).resolve().parent
MIXING2006_ROOT = MINI_PIPELINE_DIR.parents[1]
if str(MIXING2006_ROOT) not in sys.path:
    sys.path.insert(0, str(MIXING2006_ROOT))

import helpers.benchmarking.benchmark_sps_species as bss  # noqa: E402

# --- Fixture constants (must match run_smoke.sh and expected_smoke.py) ----

SMOKE_SEED = 20260830
FIXTURE_EVENTS_PER_RES = 40
MAX_DECAY_PASSES = 8
FRAGMENTATION_MODE = "both"
WEAK_FEED_POLICY = "primary_only"
DATA_SYSTEM = "pPb"

# Wounded-nucleon target for the p+Pb data system. Must stay identical to
# the --pa-* flags run_smoke.sh passes to the benchmark driver, because the
# nucleus payload is part of the cache namespace and of every component seed.
PA_NUCLEUS = {
    "name": "Pb208",
    "A": 208,
    "Z": 82,
    "profile": "woods_saxon",
    "radius_fm": 6.62,
    "diffuseness_fm": 0.546,
    "quad_alpha": 0.0,
    "sigma_nn_inel_mb": 31.7,
}

# Synthetic absolute-yield prior anchors (see module docstring): round
# numbers at the integrated-yield scale of the reduced p+Pb pion tables in
# the committed pa_data directory (data-window integrals are 58.6 and 66.2
# in the driver's invariant-window units). Sigmas are 10 percent of each
# target.
ABSYIELD_TARGETS = {"pi-": 60.0, "pi+": 65.0}
ABSYIELD_SIGMAS = {"pi-": 6.0, "pi+": 6.5}
ABSYIELD_WINDOW = {"xf_min": 0.0, "xf_max": 0.4}

DEFAULT_OUTPUT_DIR = MINI_PIPELINE_DIR / "fixture"


def build_component_cache(cache_dir: Path) -> dict[str, Path]:
    """Build the fixture cache through the production caching path."""
    specs_by_key = bss._all_resonance_specs(MIXING2006_ROOT, include_regge_tower=False)
    cache_namespace = bss._canonical_nucleus_namespace(
        dict(PA_NUCLEUS), None, data_system=DATA_SYSTEM
    )
    index = bss._build_resonance_component_cache(
        mixing2006_dir=MIXING2006_ROOT,
        cache_dir=cache_dir,
        specs_by_key=specs_by_key,
        n_events_per_res=FIXTURE_EVENTS_PER_RES,
        seed=SMOKE_SEED + 19,
        max_decay_passes=MAX_DECAY_PASSES,
        fragmentation_mode=FRAGMENTATION_MODE,
        force_rebuild=True,
        res_workers=1,
        soft_decay_overrides={},
        weak_feed_policy=WEAK_FEED_POLICY,
        nucleus=dict(PA_NUCLEUS),
        target_wound_range=None,
        cache_namespace=cache_namespace,
    )
    return index


def directory_bytes(path: Path) -> int:
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file())


def write_fixture(output_dir: Path) -> None:
    cache_dir = output_dir / "resonance_component_cache"
    index = build_component_cache(cache_dir)

    absyield_path = output_dir / "absyield_prior.json"
    absyield_path.write_text(
        json.dumps(
            {
                "window": dict(ABSYIELD_WINDOW),
                "targets": dict(ABSYIELD_TARGETS),
                "sigmas": dict(ABSYIELD_SIGMAS),
                "note": (
                    "Fixture constants for the offline mini-pipeline smoke run: "
                    "round-number absolute-yield anchors at the integrated-yield "
                    "scale of the committed reduced NA49 p+Pb pion tables. Not "
                    "measured values; regenerate via make_fixture.py."
                ),
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
        encoding="utf-8",
    )

    total_bytes = directory_bytes(cache_dir)
    manifest = {
        "generator": "sps_resonances_paper/mini_pipeline/make_fixture.py",
        "smoke_seed": SMOKE_SEED,
        "component_cache_seed": SMOKE_SEED + 19,
        "events_per_component": FIXTURE_EVENTS_PER_RES,
        "max_decay_passes": MAX_DECAY_PASSES,
        "fragmentation_mode": FRAGMENTATION_MODE,
        "weak_feed_policy": WEAK_FEED_POLICY,
        "data_system": DATA_SYSTEM,
        "nucleus": dict(PA_NUCLEUS),
        "regge_tower_disabled": True,
        "decay_lib_version": bss.RESONANCE_DECAY_LIB_VERSION,
        "n_cache_files": len(index),
        "cache_bytes": total_bytes,
    }
    (output_dir / "fixture_manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )

    print(f"fixture written: {output_dir}")
    print(f"  cache files: {len(index)}")
    print(f"  cache bytes: {total_bytes}")
    print(f"  absyield prior: {absyield_path}")


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Regenerate the committed mini-pipeline smoke fixture."
    )
    parser.add_argument(
        "--output-dir",
        default=str(DEFAULT_OUTPUT_DIR),
        help=(
            "Target directory (default: the committed mini_pipeline/fixture "
            "directory next to this script)."
        ),
    )
    args = parser.parse_args()
    output_dir = Path(args.output_dir).expanduser().resolve()
    output_dir.mkdir(parents=True, exist_ok=True)
    write_fixture(output_dir)


if __name__ == "__main__":
    main()
