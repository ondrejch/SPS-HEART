NESTED_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SMOKE_CONFIG = os.path.join(NESTED_ROOT, "config", "staged_excitation_smoke.json")
LEGACY_CARD = os.path.join(
    NESTED_ROOT, "na49_mixing", "generators", "michal", "deltas-to-pion", "delta0.gen"
)
LEGACY_N1440_CARD = os.path.join(
    NESTED_ROOT, "na49_mixing", "generators", "michal", "nstar-to-delta", "n1440-zero.gen"
)

N_EVENTS = 20  # card bound: <= 20 events per builder sample
LEGACY_SEED = 20260911


def _staged_builder_and_events():
    """20 staged p+p events from the smoke config (fit disabled)."""
    config = json.loads(open(SMOKE_CONFIG, encoding="utf-8").read())
    assert config["fit"]["enabled"] is False
    builder = PPEventBuilder(
        PPExcitationConfig(
            beam_momentum=float(config["beam_momentum"]),
            production_mode="simple",
            simple=SimpleExcitationParameters(**config["simple"]),
            regge=ReggeExcitationParameters(**config["regge"]),
            continuum=ContinuumParameters(**config["continuum"]),
        ),
        np.random.default_rng(int(config["seed"])),
    )
    events = [builder.generate(i) for i in range(N_EVENTS)]
    return builder, events


def _legacy_events():
    """20 legacy events via the ``Generator`` path and the smallest
    legacy generator card.  One ``Event`` per sample; the decay chain
    is the bundled soft-resonance library."""
    rng = np.random.default_rng(LEGACY_SEED)
    generator = Generator(reaction=Reaction(158.0), rng=rng)
    generator.set_all(LEGACY_CARD)
    decay_chain = dict(build_soft_resonance_decays(rng))
    events = []
    for _ in range(N_EVENTS):
        primary = generator.generate()
        assert primary is not None, "legacy Generator failed to produce a primary"
        event = Event(rng=rng)
        event._decay_chain = dict(decay_chain)
        event.add_particle(primary)
        event.mark_primary(primary)
        event.decay_cascade(max_passes=8)
        events.append(event)
    return events


def _hand_built_vertex_event(parent_pdg: int, d1_pdg: int, d2_pdg: int) -> Event:
    """Hand-build one closed two-body vertex (REV-158922b-03 probes).

    The parent sits at rest; the daughters carry back-to-back
    momenta of the parent-rest two-body kinematics, so the
    four-momentum and mass-shell checks close at ~1e-16, far under
    the 1e-10 audit tolerance.  The event mimics the layout the decay
    engine leaves after a cascade pass: the parent is removed from
    the live particle list, the daughters remain with the ``.parent``
    link and the ancestry stamps ``Event._stamp_ancestry`` would set
    (depth 1; weak-feed tag when the parent is declared weak).  The
    B/Q/S closure at the vertex is whatever the daughter PDG ids
    give; the probes pick ids that isolate each quantum-number
    residual.
    """
    m_parent = get_mass(parent_pdg)
    m1 = get_mass(d1_pdg)
    m2 = get_mass(d2_pdg)
    assert m1 + m2 < m_parent, "probe vertex is kinematically open"
    e1 = (m_parent * m_parent + m1 * m1 - m2 * m2) / (2.0 * m_parent)
    p_star = math.sqrt(e1 * e1 - m1 * m1)

    parent = Particle.from_id(0.0, 0.0, 0.0, parent_pdg)
    event = Event()
    event.add_particle(parent)
    event.mark_primary(parent)
    weak_feed = 1 if parent_pdg in WEAK_DECAY_PARENTS else 0
    for pdg_id, pz in ((d1_pdg, p_star), (d2_pdg, -p_star)):
        daughter = Particle.from_id(0.0, 0.0, pz, pdg_id)
        daughter.parent = parent
        daughter.set_gen_depth(1)
        daughter.set_weak_feed(weak_feed)
        event.add_particle(daughter)
    event.remove(parent)  # the cascade engine drops decayed parents
    return event


def _assert_clean(report: VertexAuditReport) -> None:
    assert report.verdict == "pass"
    assert report.four_momentum["n_failed"] == 0
    assert report.bqs["n_failed"] == 0
    assert report.bqs["residuals"] == []
    assert report.mass_shell["n_failed"] == 0
    assert report.ancestry["acyclic"] is True
    assert report.ancestry["complete"] is True
    assert report.ancestry["orphan_count"] == 0
    assert report.ancestry["cycle_count"] == 0


def test_staged_event_audit_pass():
    """Every audit on the 20-event staged smoke sample passes all four
    checks with no failure recorded."""
    _builder, events = _staged_builder_and_events()
    reports = []
    for event in events:
        report = audit_staged_event(event)
        _assert_clean(report)
        assert report.n_vertices == len(event.sources) > 0
        assert report.four_momentum["n_checked"] == report.n_vertices
        assert report.bqs["n_checked"] == report.n_vertices
        assert report.mass_shell["n_checked"] == len(event.final_particles) > 0
        reports.append(report)
    summary = vertex_audit_summary(reports)
    assert summary["all_pass"] is True
    assert summary["n_events"] == N_EVENTS
    assert summary["conservation_failures"] == 0
    assert summary["offshell_daughters"] == 0
    assert summary["bqs_residual_nonzero"] == 0
    assert summary["ancestry_violations"] == 0
    # Far below the 1e-10 audit tolerance: the staged builders already
    # enforce per-vertex closure at the same tolerance.
    assert summary["max_four_momentum_relative_residual"] <= 1e-10
    assert summary["max_mass_shell_relative_deviation"] <= 1e-10


def test_staged_event_mutation_detected():
    """Shifting one daughter's energy component on a detached copy
    flags the four-momentum and the mass-shell checks; the original
    event still audits clean."""
    _builder, events = _staged_builder_and_events()
    event = events[0]
    assert audit_staged_event(event).verdict == "pass"

    mutated = copy.deepcopy(event)
    target = mutated.final_particles[0]
    p4 = target.p4
    shift = 1e-6
    target.p4 = FourVector(p4.e + shift, p4.px, p4.py, p4.pz)

    report = audit_staged_event(mutated)
    assert report.verdict == "fail"
    assert report.four_momentum["n_failed"] >= 1
    assert report.mass_shell["n_failed"] >= 1

    # Detached: the original event is unchanged and still passes.
    assert event.final_particles[0].p4 == p4
    assert audit_staged_event(event).verdict == "pass"


def _staged_spectator_event(
    pdg_ids: tuple[int, ...], source_claim: tuple[int, int | None] = (-1, None)
) -> ExcitationEvent:
    """Hand-built staged event with no sources: each spectator sits at
    rest on its PDG mass shell (the REV-158922b-04 probes).

    ``source_claim`` is the ``(source_id, parent_id)`` pair stamped on
    every spectator; the p+A builder's no-source sentinel
    ``(-1, None)`` is the well-formed default.
    """
    spectators = [
        FinalParticle(
            particle_id=i,
            pdg_id=pid,
            p4=FourVector(get_mass(pid), 0.0, 0.0, 0.0),
            source_id=source_claim[0],
            parent_id=source_claim[1],
            channel_family="spectator",
            generation=0,
        )
        for i, pid in enumerate(pdg_ids)
    ]
    return ExcitationEvent(
        event_id=0,
        stage="baryon_nucleus",
        incoming=[],
        incoming_quantum_numbers=QuantumNumbers(0, 0, 0),
        sources=[],
        spectators=spectators,
    )


def test_staged_spectator_on_shell_and_ancestry():
    """Spectators receive the same PDG on-shell check and pass the
    ancestry walk as the builder's no-source sentinel (REV-158922b-04)."""
    event = _staged_spectator_event((2212, 2112, 2212))
    report = audit_staged_event(event)
    _assert_clean(report)
    assert report.n_vertices == 0
    assert report.mass_shell["n_checked"] == 3
    assert report.mass_shell["n_failed"] == 0


def test_staged_spectator_off_shell_detected():
    """A spectator whose four-vector mass drifts from the PDG mass fails
    the mass-shell check and the verdict (REV-158922b-04)."""
    event = _staged_spectator_event((2212, 2112))
    assert audit_staged_event(event).verdict == "pass"

    spectator = event.spectators[0]
    p4 = spectator.p4
    spectator.p4 = FourVector(p4.e + 1e-3, p4.px, p4.py, p4.pz)
    report = audit_staged_event(event)
    assert report.verdict == "fail"
    assert report.mass_shell["n_checked"] == 2
    assert report.mass_shell["n_failed"] == 1


def test_staged_spectator_orphan_ancestry():
    """A spectator that claims an unresolvable source or parent source is
    an orphan; the no-source sentinel is complete (REV-158922b-04)."""
    event = _staged_spectator_event((2212,), source_claim=(7, None))
    report = audit_staged_event(event)
    assert report.ancestry["complete"] is False
    assert report.ancestry["orphan_count"] == 1
    assert report.verdict == "fail"

    claimed = _staged_spectator_event((2212,), source_claim=(-1, 7))
    report = audit_staged_event(claimed)
    assert report.ancestry["complete"] is False
    assert report.ancestry["orphan_count"] == 1
    assert report.verdict == "fail"


def test_legacy_event_audit_pass():
    """Every audit on the 20-event legacy Generator sample passes all
    four checks; ancestry terminates at primaries."""
    events = _legacy_events()
    reports = []
    for event in events:
        tracks = event.particles()
        assert 1 <= len(tracks) <= 3  # one Delta0 primary -> nucleon + pion
        for track in tracks:
            assert track.get_gen_depth() >= 0
            assert track.get_is_primary() or track.parent is not None
        report = audit_legacy_event(event)
        _assert_clean(report)
        reports.append(report)
    summary = vertex_audit_summary(reports)
    assert summary["all_pass"] is True
    assert summary["n_events"] == N_EVENTS
    assert summary["n_vertices"] == sum(report.n_vertices for report in reports)
    assert summary["conservation_failures"] == 0
    assert summary["offshell_daughters"] == 0
    assert summary["bqs_residual_nonzero"] == 0
    assert summary["ancestry_violations"] == 0
    assert summary["max_four_momentum_relative_residual"] <= 1e-10
    assert summary["max_mass_shell_relative_deviation"] <= 1e-10


def test_legacy_cascade_vertices_reconstructed():
    """Regression (REV-158922b-01): a two-level legacy cascade is
    audited as complete vertices, not as a leftover terminal.

    One N*(1440) event from ``nstar-to-delta/n1440-zero.gen`` cascades
    through ``build_soft_resonance_decays`` into N* -> Delta + pi and
    then Delta -> N + pi: two decays, three terminals, and the
    intermediate Delta removed from the live particle list.  Grouping
    only the terminals by ``.parent`` leaves the outer vertex as
    N* -> [pi] and false-fails the four-momentum and B/Q/S closures;
    the audit must instead recover N* -> [Delta, pi] and
    Delta -> [N, pi] from the parent-chain graph and pass.
    """
    rng = np.random.default_rng(LEGACY_SEED)
    generator = Generator(reaction=Reaction(158.0), rng=rng)
    generator.set_all(LEGACY_N1440_CARD)
    decay_chain = dict(build_soft_resonance_decays(rng))
    event = Event(rng=rng)
    event._decay_chain = dict(decay_chain)
    primary = generator.generate()
    assert primary is not None
    assert primary.get_id() == 12112
    event.add_particle(primary)
    event.mark_primary(primary)
    assert event.decay_cascade(max_passes=8) == 2

    # Two decay levels: the direct pi+ daughter of the N* survives, and
    # the intermediate Delta has itself decayed away while its two
    # daughters remain, carrying the recovered ``.parent`` links.
    tracks = event.particles()
    assert len(tracks) == 3
    assert sorted(track.get_gen_depth() for track in tracks) == [1, 2, 2]
    by_parent: dict[int, list[int]] = {}
    for track in tracks:
        assert track.parent is not None
        by_parent.setdefault(track.parent.get_id(), []).append(track.get_id())
    assert by_parent == {12112: [211], 1114: [2112, -211]}

    report = audit_legacy_event(event)
    # Two complete vertices: N* -> [Delta, pi] and Delta -> [N, pi].
    # The recovered intermediate Delta is mass-shell-checked once as an
    # outer-vertex daughter, so four daughters are checked in total,
    # not the three terminals.
    assert report.n_vertices == 2
    assert report.mass_shell["n_checked"] == 4
    _assert_clean(report)


def test_weak_vertex_strangeness_exempt():
    """REV-158922b-03: a nonzero strangeness residual at a declared
    weak vertex must not fail the audit.

    Hand-built Lambda -> p + pi- vertex: B and Q close exactly, S
    does not (the weak decay changes strangeness by design,
    S_residual = -1).  The independent quantum-number asserts pin
    that this is a genuinely non-closing S vertex, so a passing
    verdict exercises the exemption rather than a vacuous zero
    residual.
    """
    parent, d1, d2 = 3122, 2212, -211  # Lambda -> p + pi-
    assert quantum_numbers(parent).S != quantum_numbers(d1).S + quantum_numbers(d2).S
    assert quantum_numbers(parent).B == quantum_numbers(d1).B + quantum_numbers(d2).B
    assert quantum_numbers(parent).Q == quantum_numbers(d1).Q + quantum_numbers(d2).Q

    report = audit_legacy_event(_hand_built_vertex_event(parent, d1, d2))
    assert report.n_vertices == 1
    assert report.bqs["n_checked"] == 1
    assert report.bqs["n_failed"] == 0
    assert report.bqs["residuals"] == []
    _assert_clean(report)


def test_weak_vertex_baryon_and_charge_still_exact():
    """REV-158922b-03 (complement): the weak-vertex exemption covers
    strangeness only; B and Q stay exact at the same vertex.

    The same hand-built Lambda vertex with a charge residual
    (p + pi+: Q_residual = -2) or a baryon-number residual
    (pi+ + pi-: B_residual = 1) must fail the audit.  Four-momentum
    and mass shell still close on both probes, so the failing
    verdict is driven purely by the exact B/Q closure.
    """
    report = audit_legacy_event(_hand_built_vertex_event(3122, 2212, 211))
    assert report.verdict == "fail"
    assert report.bqs["n_failed"] == 1
    assert report.bqs["residuals"] == [(0, -2, -1)]
    assert report.four_momentum["n_failed"] == 0
    assert report.mass_shell["n_failed"] == 0
    assert report.ancestry["acyclic"] is True
    assert report.ancestry["complete"] is True

    report = audit_legacy_event(_hand_built_vertex_event(3122, 211, -211))
    assert report.verdict == "fail"
    assert report.bqs["n_failed"] == 1
    assert report.bqs["residuals"] == [(1, 0, -1)]
    assert report.four_momentum["n_failed"] == 0
    assert report.mass_shell["n_failed"] == 0
    assert report.ancestry["acyclic"] is True
    assert report.ancestry["complete"] is True


def test_weak_vertex_exemption_keyed_on_declared_parents():
    """REV-158922b-03 (boundary): the exemption is keyed on the
    declared weak-parent list, not on the strangeness residual.

    A Sigma0 -> n + pi0 vertex has the same S = -1 -> 0 non-closure
    as the exempted Lambda vertex, but Sigma0 (3212) is not in
    ``WEAK_DECAY_PARENTS``; the audit keeps S exact there and fails
    on the nonzero strangeness residual.
    """
    report = audit_legacy_event(_hand_built_vertex_event(3212, 2112, 111))
    assert report.verdict == "fail"
    assert report.bqs["n_failed"] == 1
    assert report.bqs["residuals"] == [(0, 0, -1)]
    assert report.four_momentum["n_failed"] == 0
    assert report.mass_shell["n_failed"] == 0


def test_ancestry_acyclic_complete():
    """The generated staged ancestry graph is acyclic and complete, and
    synthetic broken events are flagged."""
    _builder, events = _staged_builder_and_events()
    event = events[0]
    source_ids = {source.source_id for source in event.sources}
    for particle in event.final_particles:
        assert particle.parent_id in source_ids
    report = audit_staged_event(event)
    assert report.ancestry["acyclic"] is True
    assert report.ancestry["complete"] is True
    assert report.ancestry["orphan_count"] == 0
    assert report.ancestry["cycle_count"] == 0
    assert report.verdict == "pass"

    # Synthetic probe 1: a final particle whose parent_id does not
    # resolve to a present source record.
    orphaned = ExcitationEvent(
        event_id=0,
        stage="simple",
        incoming=[FourVector(1.0, 0.0, 0.0, 0.0), FourVector(1.0, 0.0, 0.0, 0.0)],
        incoming_quantum_numbers=QuantumNumbers(2, 2, 0),
        sources=[
            SourceRecord(
                0,
                "projectile",
                FourVector(1.0, 0.0, 0.0, 0.5),
                QuantumNumbers(1, 1, 0),
            )
        ],
        final_particles=[
            FinalParticle(
                particle_id=0,
                pdg_id=211,
                p4=FourVector(get_mass(211), 0.0, 0.0, 0.0),
                source_id=0,
                parent_id=7,  # no such source
                channel_family="test",
            )
        ],
    )
    orphan_report = audit_staged_event(orphaned)
    assert orphan_report.ancestry["complete"] is False
    assert orphan_report.ancestry["orphan_count"] == 1
    assert orphan_report.verdict == "fail"

    # Synthetic probe 2: a source that is its own parent.
    cyclic = ExcitationEvent(
        event_id=0,
        stage="simple",
        incoming=[FourVector(1.0, 0.0, 0.0, 0.0), FourVector(1.0, 0.0, 0.0, 0.0)],
        incoming_quantum_numbers=QuantumNumbers(2, 2, 0),
        sources=[
            SourceRecord(
                0,
                "projectile",
                FourVector(1.0, 0.0, 0.0, 0.5),
                QuantumNumbers(1, 1, 0),
                parent_source_id=0,  # self-parent cycle
            )
        ],
        final_particles=[],
    )
    cyclic_report = audit_staged_event(cyclic)
    assert cyclic_report.ancestry["acyclic"] is False
    assert cyclic_report.ancestry["cycle_count"] >= 1
    assert cyclic_report.verdict == "fail"

    # Synthetic probe 3: a two-source cycle (0 -> 1 -> 0).
    two_cycle = ExcitationEvent(
        event_id=0,
        stage="simple",
        incoming=[FourVector(1.0, 0.0, 0.0, 0.0), FourVector(1.0, 0.0, 0.0, 0.0)],
        incoming_quantum_numbers=QuantumNumbers(2, 2, 0),
        sources=[
            SourceRecord(
                0,
                "projectile",
                FourVector(1.0, 0.0, 0.0, 0.5),
                QuantumNumbers(1, 1, 0),
                parent_source_id=1,
            ),
            SourceRecord(
                1,
                "target",
                FourVector(1.0, 0.0, 0.0, -0.5),
                QuantumNumbers(1, 1, 0),
                parent_source_id=0,
            ),
        ],
        final_particles=[],
    )
    two_cycle_report = audit_staged_event(two_cycle)
    assert two_cycle_report.ancestry["acyclic"] is False
    assert two_cycle_report.ancestry["cycle_count"] == 2


def test_summary_reduction():
    """``vertex_audit_summary`` aggregates hand-built reports exactly."""
    clean = VertexAuditReport(
        event_index=0,
        n_vertices=2,
        four_momentum={"n_checked": 2, "n_failed": 0, "max_relative_residual": 1.0e-15},
        bqs={"n_checked": 2, "n_failed": 0, "residuals": []},
        mass_shell={"n_checked": 4, "n_failed": 0, "max_relative_deviation": 3.0e-15},
        ancestry={"acyclic": True, "complete": True, "orphan_count": 0, "cycle_count": 0},
        verdict="pass",
    )
    failing = VertexAuditReport(
        event_index=1,
        n_vertices=3,
        four_momentum={"n_checked": 3, "n_failed": 1, "max_relative_residual": 1.0e-6},
        bqs={"n_checked": 3, "n_failed": 1, "residuals": [(0, 1, 0)]},
        mass_shell={"n_checked": 5, "n_failed": 2, "max_relative_deviation": 7.0e-6},
        ancestry={"acyclic": True, "complete": False, "orphan_count": 1, "cycle_count": 0},
        verdict="fail",
    )
    shallow = VertexAuditReport(
        event_index=2,
        n_vertices=0,
        four_momentum={"n_checked": 0, "n_failed": 0, "max_relative_residual": 0.0},
        bqs={"n_checked": 0, "n_failed": 0, "residuals": []},
        mass_shell={"n_checked": 0, "n_failed": 0, "max_relative_deviation": 0.0},
        ancestry={"acyclic": True, "complete": True, "orphan_count": 0, "cycle_count": 0},
        verdict="pass",
    )
    summary = vertex_audit_summary([clean, failing, shallow])
    assert summary == {
        "n_events": 3,
        "n_vertices": 5,
        "conservation_failures": 1,
        "offshell_daughters": 2,
        "bqs_residual_nonzero": 1,
        "ancestry_violations": 1,
        "max_four_momentum_relative_residual": 1.0e-6,
        "max_mass_shell_relative_deviation": 7.0e-6,
        "all_pass": False,
    }
    empty = vertex_audit_summary([])
    assert empty["n_events"] == 0
    assert empty["all_pass"] is True
    assert empty["max_four_momentum_relative_residual"] == 0.0
    assert empty["max_mass_shell_relative_deviation"] == 0.0


