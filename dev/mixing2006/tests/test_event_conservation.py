"""Per-vertex conservation audit tests (Round 1, card
TASK-20260911-r1-vertex-conservation-audit).

The audit module ``na49_mixing.event_conservation`` walks the decay
vertices of generated events and checks, per vertex, the four-momentum
and ``(B, Q, S)`` closures, the daughter mass shells, and the ancestry
conditions (acyclicity and completeness).  These tests pin that
behavior on deterministic samples only:

- the staged p+p sample is generated by ``PPEventBuilder`` from
  ``config/staged_excitation_smoke.json`` (``fit.enabled`` false) with
  one seed and 20 events;
- the legacy sample is generated by the legacy ``Generator`` path from
  the smallest legacy generator card bundled in the repository
  (``na49_mixing/generators/michal/deltas-to-pion/delta0.gen``, 198
  bytes) with one seed and 20 events, cascaded through
  ``build_soft_resonance_decays``;
- the cascade regression pins the two-level legacy cascade of
  ``na49_mixing/generators/michal/nstar-to-delta/n1440-zero.gen`` (one
  event, seed 20260911): N* -> Delta + pi followed by Delta -> N + pi
  must be audited as two complete vertices;
- the mutation probe acts on a detached deep copy of one staged event,
  never on the original;
- the ancestry probes are small hand-built events, not mutated
  generated events;
- the spectator probes (REV-158922b-04) are small hand-built staged
  events with p+A spectator nucleons; they pin the PDG on-shell check
  and the ancestry sentinel semantics of ``event.spectators``;
- the weak-vertex probes (REV-158922b-03) are hand-built two-body
  vertices (Lambda and Sigma0 parents) with closed four-momentum and
  mass-shell kinematics; they pin the strangeness exemption at
  declared ``WEAK_DECAY_PARENTS`` vertices, the exact B and Q closure
  that stays in force there, and the declared-parent keying of the
  exemption itself.

Hermetic: no external tables, no fit, no event generation beyond the
two 20-event samples.
"""

